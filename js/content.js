// Hebrew tiles carry no final forms; restore them when a word is shown as text.
const FINALS = { 'כ': 'ך', 'מ': 'ם', 'נ': 'ן', 'פ': 'ף', 'צ': 'ץ' };
export const pretty = (lang, w) =>
  lang === 'he' && FINALS[w[w.length - 1]] ? w.slice(0, -1) + FINALS[w[w.length - 1]] : w;
